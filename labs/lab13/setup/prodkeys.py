#!/usr/bin/env python3
"""Lab 13.1 step 2 - generate the replica-set keyfile (and the service passwords + Prometheus config).

Run once by the `lab13-keyfile` container of docker-compose.yml, BEFORE the three mongod containers start:

    python labs/lab13/setup/prodkeys.py init --keys /keys --out /prod --mon /monitoring

    /keys/keyfile            openssl rand -base64 756 > keyfile   (the classroom command)
                             chown 999:999 keyfile + chmod 400 keyfile   (999 = the mongodb user of the mongo:7.0 image)
                             -> volume lab13-keyfile, mounted ONLY into prod-mongo-1/2/3 at /etc/mongodb (read-only)
    /prod/secrets.json       random passwords of admin, lab_app, billing_app, exporter (mode 600)
                             -> volume lab13-prod, mounted into the lab containers and the exporter sidecar
    /monitoring/*.yml        prometheus.yml + alerts.yml (mode 644, readable by the prometheus user)
                             -> volume lab13-monitoring, mounted only into the prometheus container

Why not the classroom's bind mount `./keyfile:/etc/mongodb/keyfile:ro`?  mongod runs as uid 999 and refuses a keyfile it
cannot read or whose permissions are open to the group/world. A host file made with `chmod 400` belongs to the host user
(uid 1000 on Linux, root through Docker Desktop's file sharing), so uid 999 cannot read it ("permission denied") unless it
is also chown-ed to 999 on the host. Generating it inside a named volume with the right owner avoids that on every OS.

Idempotent: an existing keyfile / secrets file is never replaced (the users on the server are bound to those passwords).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import secrets
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

USERS = ("admin", "lab_app", "billing_app", "exporter", "monitor_app", "backup_app", "tasktracker_app")   # + Lab 14, Lab 15
MONGO_UID = MONGO_GID = 999

PROMETHEUS = """# Lab 13 activity - Prometheus scrapes the exporter sidecar of prod-mongo-1 (generated by prodkeys.py)
global:
  scrape_interval: 5s
  evaluation_interval: 5s
  external_labels:
    lab: "lab13"
rule_files:
  - /etc/lab13/alerts.yml
scrape_configs:
  - job_name: mongodb
    metrics_path: /metrics
    static_configs:
      - targets: ["prod-mongo-1:9216"]      # the sidecar shares prod-mongo-1's network namespace
        labels:
          member: prod-mongo-1
          replset: rs0
  - job_name: prometheus
    static_configs:
      - targets: ["localhost:9090"]
"""

ALERTS = """# Lab 13 activity - alerting rules evaluated by Prometheus (see http://localhost:9090/alerts)
groups:
  - name: mongodb
    rules:
      - alert: MongoDBExporterDown
        expr: up{job="mongodb"} == 0
        for: 10s
        labels: {severity: critical}
        annotations:
          summary: "The exporter sidecar of {{ $labels.member }} cannot be scraped"
      - alert: MongoDBDown
        expr: mongodb_up == 0
        for: 10s
        labels: {severity: critical}
        annotations:
          summary: "mongod {{ $labels.member }} does not answer the exporter"
      - alert: ReplicaSetMemberNotHealthy
        expr: max by (member_idx) (mongodb_rs_members_health) == 0
        for: 10s
        labels: {severity: warning}
        annotations:
          summary: "Replica-set member {{ $labels.member_idx }} is not healthy"
      - alert: ReplicaSetNoPrimary
        expr: absent(mongodb_rs_members_state == 1)
        for: 15s
        labels: {severity: critical}
        annotations:
          summary: "No PRIMARY in replica set rs0 (election in progress or majority lost)"
"""


def _keyfile(keys: Path, log) -> dict:
    keys.mkdir(parents=True, exist_ok=True)
    kf = keys / "keyfile"
    if kf.exists() and kf.stat().st_size > 0:
        log(f"keyfile exists: {kf} - kept (a new key would lock the running members out of each other)")
    else:
        cmd = ["openssl", "rand", "-base64", "756"]
        log("$ " + " ".join(cmd) + f" > {kf}")
        out = subprocess.run(cmd, capture_output=True, check=True).stdout
        kf.write_bytes(out)
    os.chown(kf, MONGO_UID, MONGO_GID)
    os.chmod(kf, 0o400)
    log(f"$ chown {MONGO_UID}:{MONGO_GID} {kf} && chmod 400 {kf}")
    st = kf.stat()
    raw = kf.read_bytes()
    chars = len(b"".join(raw.split()))
    return {"path": "/etc/mongodb/keyfile", "mode": oct(st.st_mode & 0o777), "uid": st.st_uid, "gid": st.st_gid,
            "bytes": st.st_size, "base64_chars": chars, "sha256": hashlib.sha256(raw).hexdigest()}


def _secrets(out: Path, log) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    p = out / "secrets.json"
    data = json.loads(p.read_text()) if p.exists() else {}
    made = [u for u in USERS if u not in data]
    for u in made:
        data[u] = secrets.token_urlsafe(18)          # 24 URL-safe characters, ~144 bits
    data.setdefault("created_at", datetime.now(timezone.utc).isoformat())
    p.write_text(json.dumps(data, indent=2))
    os.chmod(p, 0o600)
    os.chmod(out, 0o755)
    log(f"secrets.json: {', '.join(made) if made else 'all passwords already exist'} (mode 600)")
    return {"path": str(p), "users": list(USERS), "created": made}


def _monitoring(mon: Path, log) -> dict:
    mon.mkdir(parents=True, exist_ok=True)
    for name, body in (("prometheus.yml", PROMETHEUS), ("alerts.yml", ALERTS)):
        f = mon / name
        f.write_text(body)
        os.chmod(f, 0o644)
    os.chmod(mon, 0o755)
    log(f"prometheus.yml + alerts.yml written to {mon}")
    return {"files": ["prometheus.yml", "alerts.yml"]}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("init")
    i.add_argument("--keys", default="/keys")
    i.add_argument("--out", default="/prod")
    i.add_argument("--mon", default="/monitoring")
    s = sub.add_parser("show")
    s.add_argument("--keys", default="/keys")
    a = ap.parse_args()
    log = lambda m: print(f"[lab13-keyfile] {m}", flush=True)   # noqa: E731
    if a.cmd == "init":
        info = {"keyfile": _keyfile(Path(a.keys), log), "secrets": _secrets(Path(a.out), log),
                "monitoring": _monitoring(Path(a.mon), log)}
        (Path(a.out) / "keyfile-info.json").write_text(json.dumps(info["keyfile"], indent=2))
        k = info["keyfile"]
        log(f"keyfile ready: mode {k['mode'][2:]}, owner {k['uid']}:{k['gid']}, {k['bytes']} bytes "
            f"({k['base64_chars']} base64 characters), sha256 {k['sha256'][:16]}...")
    else:
        kf = Path(a.keys) / "keyfile"
        print(json.dumps({"exists": kf.exists(), "mode": oct(kf.stat().st_mode & 0o777) if kf.exists() else None}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
