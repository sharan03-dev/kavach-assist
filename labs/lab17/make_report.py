"""Builds results/Exercise-17_Report.pdf (the Docker Hub URL is on page 1).   python labs/lab17/make_report.py"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from report_kit import (W, P, Paragraph, box, arrow, build_doc, checks, code_block, curve, esc, header, mm, styles, tbl,  # noqa: E402
                        Drawing, Rect, String, colors, BLUE)
from reportlab.platypus import PageBreak  # noqa: E402

TITLE = "AI-Native MongoDB: Vector Search and RAG Foundations"
NOTES = [
    "Atlas Vector Search builds HNSW graphs only; there is no indexOption {type: 'ivf'} - the IVF index in this lab is built inside MongoDB (k-means lists + an indexed list id).",
    "In an Atlas vectorSearch index definition the HNSW knobs are hnswOptions.maxEdges (M) and hnswOptions.numEdgeCandidates (efConstruction), not indexOption {type: 'hnsw', M, efConstruction}; if this server refused them, the notes of 17.2 say so.",
    "numDimensions must equal the embedding model: the sample index says 1536, voyage-3 returns 1024 and all-MiniLM-L6-v2 384 dimensions.",
    "numCandidates must be >= limit (the solution's numCandidates 20, limit 3 is valid); exact: true gives exact (ENN) search for ground truth.",
    "Recall is counted against an exact brute-force search over the same vectors; ties (identical sentences) count as correct when equally similar.",
    "A follow-up question ('how can we reduce them?') retrieves nothing useful on its own; the stored history is used to rewrite it before retrieval.",
    "Without an API key the answer is generated by a built-in extractive model (sentences of the retrieved chunks, cited); set ANTHROPIC_API_KEY or OLLAMA_URL for an LLM.",
]


def architecture():
    d = Drawing(500, 150)
    d.add(Rect(2, 2, 496, 146, fillColor=colors.HexColor("#eef3fb"), strokeColor=None))
    d.add(String(8, 138, "Lab 17 - retrieval augmented generation on MongoDB Atlas Local (mongod + mongot)", fontSize=7.5, fontName="Helvetica-Bold"))
    steps = [["5 TI documents", "100-word chunks", "20-word overlap"], ["Embedding model", "MiniLM-L6 (384 d)", "or Voyage / hashing"],
             ["rag_demo.documents", "{text, source, embedding}", "vectorSearch index"], ["$vectorSearch", "numCandidates 20", "limit 3"], ["Prompt -> LLM", "answer + [1][2][3]", "citations"]]
    for i, s in enumerate(steps):
        box(d, 8 + i * 98, 82, 88, 42, s, fill="#ffffff", size=6.1)
        if i:
            arrow(d, 8 + i * 98 - 10, 103, 8 + i * 98, 103, BLUE)
    box(d, 8, 14, 236, 50, ["Activity: rag_demo.conversations {user_id, timestamp,", "role, content} - last 5 exchanges in the prompt,", "follow-ups rewritten with the previous question"], fill="#fff4dc", size=6.1)
    box(d, 254, 14, 238, 50, ["17.2: 5,000 x 384-d vectors - HNSW (mongot) vs", "IVF (k-means lists in MongoDB) vs exact search;", "applied to Lab 7: Ask Kavach over the threat reports"], fill="#fff4dc", size=6.1)
    return d


def build(out: dict, results: Path, docker_url: str) -> Path:
    st = styles()
    e = header(st, 17, TITLE, docker_url,
               "docker compose up -d lab17                  # Lab 7 -> ... -> 16 -> 17 (+ MongoDB Atlas Local with mongot)\n"
               "open http://localhost:8000/#/lab17          # RAG, chat with memory, HNSW vs IVF, Ask Kavach\n"
               "docker compose exec lab17 lab17 all         # every Lab 17 task + this report", out.get("environment"))
    e += checks(out, st)
    e += [Paragraph("Architecture", st["h1"]), architecture()]
    a = out.get("lab_17_1") or {}
    if a.get("build"):
        b = a["build"]
        e += [PageBreak(), Paragraph("Lab 17.1 - Build a simple RAG pipeline", st["h1"]),
              Paragraph(f"(1) {len(b['documents'])} documents about threat intelligence, chunked into {b['chunks']} segments of at most 100 words "
                        f"(sizes {esc(', '.join(map(str, b['chunk_sizes'])))}). (2) Embeddings: {esc(b['embedder']['provider'])} - {esc(b['embedder']['model'])}, "
                        f"{b['embedder']['dims']} dimensions; stored with text and source in rag_demo.documents; vector index "
                        + (f"queryable after {b['index']['build_s']} s." if b['index'].get('build_s') else "not available (exact NumPy search used).") +
                        " (3) retrieve() embeds the query and runs $vectorSearch with numCandidates 20, limit 3. (4) The prompt 'Answer based on these documents: "
                        "{chunks}. Question: {query}' goes to the generator: " + esc(f"{a['generator']['provider']} ({a['generator']['model']})") + ".", st["p"]),
              tbl([["Document", "Words"]] + [[esc(d["title"]), d["words"]] for d in b["documents"]], [W - 20 * mm, 20 * mm])]
        e += code_block(json.dumps(b["index"].get("definition", {}), indent=1)[:900], st)
        e += [Paragraph(f"Retrieval evaluation: right document first for {a['hit_at_1']}/{a['questions']}, in the top 3 for {a['hit_at_3']}/{a['questions']} ({esc(a['mode'])})", st["h2"]),
              tbl([["Question", "Expected", "Top 3", "Hit"]] + [[P(esc(x["question"]), st), esc(x["expected"][:2]), esc(", ".join(s[:2] for s in x["top3"])), "yes" if x["hit_at_3"] else "no"] for x in a["evaluation"]],
                  [W - 66 * mm, 18 * mm, 32 * mm, 16 * mm]),
              Paragraph("One full round trip", st["h2"]), Paragraph(f"<b>Q:</b> {esc(a['demo']['question'])}", st["p"]), Paragraph(f"<b>A:</b> {esc(a['demo']['answer'])}", st["p"])]
    m = out.get("memory") or {}
    if m.get("turns"):
        e += [Paragraph("Activity 17.1 - conversation memory", st["h1"]),
              Paragraph("Each query and answer is stored in rag_demo.conversations {user_id, timestamp, role, content, sources} (index user_id + timestamp). Before generating, "
                        f"the last 5 exchanges (10 messages) are read back and placed in the prompt. {m['stored_messages']} messages stored; window {m['window']} messages.", st["p"]),
              tbl([["#", "Question", "History", "Retrieval query (rewritten)", "Top document"]] +
                  [[i + 1, P(esc(t["question"]), st), t["history_used"], P(esc(t["retrieval_query"]), st), esc((t["top_source"] or "")[:28])] for i, t in enumerate(m["turns"])],
                  [8 * mm, 46 * mm, 14 * mm, W - 116 * mm, 48 * mm])]
    c = out.get("lab_17_2") or {}
    if c.get("rows"):
        cols = [colors.HexColor(x) for x in ("#ffb000", "#e8590c", "#d6336c", "#13aa52", "#1287b1")]
        series = [(f"HNSW {k.replace('hnsw_', '')}", cols[i], [(p["latency_ms"], p["recall"]) for p in v]) for i, (k, v) in enumerate((c["curve"].get("HNSW") or {}).items())]
        series += [(f"IVF {k.replace('ivf_', '')}", cols[3 + i], [(p["latency_ms"], p["recall"]) for p in v]) for i, (k, v) in enumerate((c["curve"].get("IVF") or {}).items())]
        e += [PageBreak(), Paragraph("Lab 17.2 - Compare HNSW and IVF vector index types", st["h1"]),
              Paragraph(f"{c['n']:,} documents ({c['corpus']['real']:,} sentences from the Kavach reports and vulnerabilities, {c['corpus']['generated']:,} generated), "
                        f"{c['dims']}-dimensional embeddings ({esc(c['embedder']['provider'])}), inserted with insert_many in batches of 500 ({c['insert_s']} s). "
                        f"{c['queries']} queries (random document embeddings) per configuration; latency with time.perf_counter(); recall@20 = |found AND true top 20| / 20 "
                        "against an exact brute-force scan of all documents.", st["p"]),
              tbl([["Index", "How it is built here"],
                   ["HNSW", P("Atlas Vector Search index (mongot): {type: 'vector', path: 'embedding', numDimensions, similarity: 'cosine', hnswOptions: {maxEdges, numEdgeCandidates}}; "
                              "query-time knob numCandidates", st)],
                   ["IVF", P("k-means (spherical, 20 rounds) into nlist lists; centroids in ivf_centroids, list id on every document (indexed); a query scans the nprobe closest lists", st)],
                   ["Exact", P("$vectorSearch exact: true (ENN) and NumPy brute force (the ground truth)", st)]], [18 * mm, W - 18 * mm]),
              curve(series, "latency-recall trade-off (up and to the left is better)"),
              tbl([["Index type", "Parameters", "Build (s)", "Avg (ms)", "p95 (ms)", "Recall (%)"]] +
                  [[P(esc(r["index"]), st), P(esc(r["params"]), st), "-" if r["build_s"] is None else r["build_s"], f"{r['avg_ms']:.2f}", f"{r['p95_ms']:.2f}", f"{r['recall']:.1f}"] for r in c["rows"]],
                  [40 * mm, W - 112 * mm, 16 * mm, 18 * mm, 18 * mm, 20 * mm]),
              Paragraph("Recommendation", st["h2"])] + [Paragraph(esc(t), st["p"]) for t in c["recommendation"]["text"]]
        for n in c.get("notes") or []:
            e.append(Paragraph("<i>" + esc(n) + "</i>", st["p"]))
        if c.get("classroom_sample"):
            e += [Paragraph("The classroom sample, tested as written", st["h2"])] + [Paragraph(f"<b>{esc(k)}:</b> {esc(str(v.get('result')))}", st["p"]) for k, v in c["classroom_sample"].items()]
    ap = out.get("applied") or {}
    if ap.get("build"):
        e += [Paragraph("Applied to Lab 7 - Ask Kavach", st["h1"]),
              Paragraph(f"{ap['build']['reports']:,} Lab 7 threat reports (title + summary) embedded and indexed in kavach_rag.reports in {ap['build']['seconds']} s. "
                        "The website answers questions from the reports that are closest in meaning and cites them.", st["p"]),
              tbl([["Question", "Top report"]] + [[P(esc(q["question"]), st), P(esc(q["top"][0] if q["top"] else "-"), st)] for q in ap["questions"]], [60 * mm, W - 60 * mm])]
    e += [Paragraph("Notes on correctness", st["h1"])] + [Paragraph("- " + esc(n), st["p"]) for n in NOTES]
    return build_doc(results / "Exercise-17_Report.pdf", TITLE, 17, e)


if __name__ == "__main__":
    res = Path(os.getenv("RESULTS_DIR", str(Path(__file__).resolve().parents[2] / "results")))
    print(build(json.loads((res / "lab17_results.json").read_text()), res, os.getenv("DOCKER_URL", "")))
